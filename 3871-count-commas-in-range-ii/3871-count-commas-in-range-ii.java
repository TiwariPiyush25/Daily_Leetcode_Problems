class Solution {
    public long countCommas(long n) {
        if(n < 1000L) return 0;
        if(n >= 1000L && n<1000000L) return n - 999;
        if(n >= 1000000L && n<1000000000L) return ((n - 999999)*2) + (999999 - 999);
        if(n>=1000000000L && n<1000000000000L)  return (n - 999999999)*3 + ((999999999 - 999999)*2) + (999999 - 999);

        if(n>=1000000000000L && n <1000000000000000L)return (n - 999999999999L)*4L + (999999999999L - 999999999L)*3L + (999999999L - 999999L)*2L + (999999L - 999L);
        return (n-999999999999999L)*5L + (999999999999999L - 999999999999L)*4L + (999999999999L - 999999999L)*3L + (999999999L - 999999L)*2L + (999999L - 999L);
    }
}